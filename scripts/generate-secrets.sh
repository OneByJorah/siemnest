#!/usr/bin/env bash
# Fills in this install's secrets in .env and writes the config files derived from them.
# Safe to re-run: values already set in .env are kept. Nothing here is committed.
set -euo pipefail
cd "$(dirname "$0")/.."

USERS_FILE=wazuh/config/wazuh_indexer/internal_users.yml
API_FILE=wazuh/config/wazuh_dashboard/wazuh.yml

get() { { grep -E "^$1=" .env || true; } | tail -n 1 | cut -d= -f2- | tr -d '\r'; }
blank() { case "$(get "$1")" in '' | '<'*) return 0 ;; *) return 1 ;; esac; }
put() {
  awk -v k="$1" -v v="$2" 'index($0, k "=") == 1 { print k "=" v; found = 1; next } { print } END { if (!found) print k "=" v }' .env > .env.tmp
  mv .env.tmp .env
}
fill() { if blank "$1"; then put "$1" "$2"; fi; }

for f in "$USERS_FILE" "$API_FILE"; do
  if [ -d "$f" ]; then
    echo "==> $f is a directory, probably created by Docker. Remove it and run this again." >&2
    exit 1
  fi
done

[ -f .env ] || cp .env.example .env
chmod 600 .env

fill INDEXER_ADMIN_PASSWORD "$(openssl rand -hex 16)"
fill DASHBOARD_PASSWORD "$(openssl rand -hex 16)"
# The Wazuh API requires upper case, lower case, a digit and a symbol.
fill WAZUH_API_PASSWORD "Az9.$(openssl rand -hex 16)"
fill GRAYLOG_PASSWORD_SECRET "$(openssl rand -hex 32)"
if blank GRAYLOG_ROOT_PASSWORD_SHA2; then
  root_password="$(openssl rand -hex 16)"
  put GRAYLOG_ROOT_PASSWORD "$root_password"
  put GRAYLOG_ROOT_PASSWORD_SHA2 "$(printf %s "$root_password" | openssl dgst -sha256 -r | cut -d' ' -f1)"
fi

INDEXER_IMAGE="$(grep -m1 -oE 'wazuh/wazuh-indexer:[^ ]+' wazuh/docker-compose.yml | tr -d '\r')"
hash_password() {
  local hash
  hash="$(PW="$1" docker run --rm -e PW "$INDEXER_IMAGE" bash -c \
    'JAVA_HOME=/usr/share/wazuh-indexer/jdk /usr/share/wazuh-indexer/plugins/opensearch-security/tools/hash.sh -p "$PW"' \
    2>/dev/null | tail -n 1 | tr -d '\r')"
  case "$hash" in
    '$2'*) printf %s "$hash" ;;
    *) echo "==> Could not hash a password with $INDEXER_IMAGE" >&2; return 1 ;;
  esac
}

echo "==> Writing $USERS_FILE and $API_FILE from .env"
admin_hash="$(hash_password "$(get INDEXER_ADMIN_PASSWORD)")"
dashboard_hash="$(hash_password "$(get DASHBOARD_PASSWORD)")"

cat > "$USERS_FILE" <<EOF
---
# Generated by scripts/generate-secrets.sh. Do not edit or commit.
_meta:
  type: "internalusers"
  config_version: 2

admin:
  hash: "$admin_hash"
  reserved: true
  backend_roles:
  - "admin"
  description: "Administrator"

kibanaserver:
  hash: "$dashboard_hash"
  reserved: true
  description: "Wazuh dashboard service user"
EOF

cat > "$API_FILE" <<EOF
# Generated by scripts/generate-secrets.sh. Do not edit or commit.
hosts:
  - 1513629884013:
      url: "https://wazuh.manager"
      port: 55000
      username: wazuh-wui
      password: "$(get WAZUH_API_PASSWORD)"
      run_as: false
EOF
chmod 644 "$USERS_FILE" "$API_FILE"
